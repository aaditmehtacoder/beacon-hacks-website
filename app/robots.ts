import type { MetadataRoute } from "next";
import { EVENT } from "@/lib/event";

/* AI search and answer crawlers, named so they are welcome explicitly. They
   read the same pages, and /llms.txt has the facts in one place. */
const AI_CRAWLERS = [
  "GPTBot",
  "OAI-SearchBot",
  "ChatGPT-User",
  "ClaudeBot",
  "Claude-SearchBot",
  "Claude-User",
  "PerplexityBot",
  "Perplexity-User",
  "Google-Extended",
  "Applebot-Extended",
];

export default function robots(): MetadataRoute.Robots {
  return {
    rules: [
      { userAgent: "*", allow: "/", disallow: ["/api/"] },
      { userAgent: AI_CRAWLERS, allow: "/", disallow: ["/api/"] },
    ],
    sitemap: `${EVENT.url}/sitemap.xml`,
  };
}
